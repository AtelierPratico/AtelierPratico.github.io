from pathlib import Path
import runpy

# Start from v7.2: premium UI + expressive segmented Rive Tiko.
runpy.run_path('android-app/prepare_v72.py', run_name='__main__')

ROOT = Path('android-app')
main = ROOT / 'app/src/main/java/ai/pratico/app/MainActivity.java'
s = main.read_text(encoding='utf-8')

# 1) Normalize model names returned by the backend. This prevents accidental
#    "models/models/..." setup payloads from leaving Gemini Live stuck connecting.
old_model = '                    setup.put("model", "models/" + model);'
new_model = '''                    String normalizedModel = model == null ? "gemini-3.8-live" : model.trim();
                    if (normalizedModel.startsWith("models/")) normalizedModel = normalizedModel.substring(7);
                    if (normalizedModel.isEmpty()) normalizedModel = "gemini-3.8-live";
                    setup.put("model", "models/" + normalizedModel);'''
if old_model not in s:
    raise SystemExit('v7.3: Gemini Live model setup line not found')
s = s.replace(old_model, new_model, 1)

# 2) Add a real setup timeout. Previously the UI could remain forever on
#    "Tiko se prépare…" when Gemini accepted the WebSocket but rejected setup.
old_open_tail = '''                    webSocket.send(new JSONObject().put("setup", setup).toString());
                } catch (Exception e) {
                    runJs("window.PratikoVoice && window.PratikoVoice.onError('Erreur de préparation de la voix.')");
                    stopVoiceSession();
                }
            }
'''
new_open_tail = '''                    boolean sent = webSocket.send(new JSONObject().put("setup", setup).toString());
                    if (!sent) throw new Exception("voice setup send failed");
                    main.postDelayed(() -> {
                        if (voiceStarting && voiceSocket == webSocket) {
                            voiceStarting = false;
                            voiceActive = false;
                            try { webSocket.cancel(); } catch (Exception ignored) { }
                            if (voiceSocket == webSocket) voiceSocket = null;
                            releaseAudio();
                            runJs("window.PratikoVoice && window.PratikoVoice.onError('La connexion vocale prend trop de temps. Réessaie dans un instant.')");
                        }
                    }, 12000);
                } catch (Exception e) {
                    runJs("window.PratikoVoice && window.PratikoVoice.onError('Erreur de préparation de la voix.')");
                    stopVoiceSession();
                }
            }
'''
if old_open_tail not in s:
    raise SystemExit('v7.3: voice onOpen setup block not found')
s = s.replace(old_open_tail, new_open_tail, 1)

# 3) Gemini can return a JSON error frame without failing the WebSocket.
#    Handle it explicitly instead of silently ignoring it and staying in connecting state.
old_message_head = '''                    JSONObject msg = new JSONObject(text);
                    if (msg.has("setupComplete")) {
'''
new_message_head = '''                    JSONObject msg = new JSONObject(text);
                    JSONObject liveError = msg.optJSONObject("error");
                    if (liveError != null) {
                        String liveMessage = liveError.optString("message", "Le service vocal a refusé la connexion.");
                        voiceStarting = false;
                        voiceActive = false;
                        if (voiceSocket == webSocket) voiceSocket = null;
                        releaseAudio();
                        try { webSocket.close(1000, "gemini_error"); } catch (Exception ignored) { }
                        runJs("window.PratikoVoice && window.PratikoVoice.onError(" + JSONObject.quote(liveMessage) + ")");
                        return;
                    }
                    if (msg.has("setupComplete")) {
'''
if old_message_head not in s:
    raise SystemExit('v7.3: voice onMessage block not found')
s = s.replace(old_message_head, new_message_head, 1)

# 4) More useful failure reporting instead of an infinite spinner / generic silence.
old_failure = '''                runJs("window.PratikoVoice && window.PratikoVoice.onError('La conversation vocale a été interrompue.')");'''
new_failure = '''                String detail = (t != null && t.getMessage() != null && !t.getMessage().isEmpty()) ? t.getMessage() : "connexion interrompue";
                runJs("window.PratikoVoice && window.PratikoVoice.onError(" + JSONObject.quote("La conversation vocale a été interrompue : " + detail) + ")");'''
if old_failure not in s:
    raise SystemExit('v7.3: voice failure message not found')
s = s.replace(old_failure, new_failure, 1)

# Version metadata generated by v7.2 -> v7.3.
s = s.replace('PratikoAIAndroid/7.2', 'PratikoAIAndroid/7.3').replace('android-7.2', 'android-7.3')
main.write_text(s, encoding='utf-8')

gradle = ROOT / 'app/build.gradle'
g = gradle.read_text(encoding='utf-8').replace('versionCode 33', 'versionCode 34').replace("versionName '7.2.0'", "versionName '7.3.0'")
gradle.write_text(g, encoding='utf-8')

appjs = ROOT / 'app/src/main/assets/app.js'
a = appjs.read_text(encoding='utf-8').replace("version:'7.2'", "version:'7.3'")
appjs.write_text(a, encoding='utf-8')

print('Pratiko AI v7.3 prepared — Gemini Live voice model normalization, setup timeout and explicit WebSocket error handling')
